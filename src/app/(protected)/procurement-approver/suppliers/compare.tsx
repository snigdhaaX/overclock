import { AlternativeComparison } from '../../../../features/procurement-approver/types';
import { procurementService } from '../../../../features/procurement-approver/services/procurementService';
import ProcurementHeader from '../../../../features/procurement-approver/components/ProcurementHeader';
import ProcurementBottomNav from '../../../../features/procurement-approver/components/ProcurementBottomNav';
import SupplierComparisonCard from '../../../../features/procurement-approver/components/SupplierComparisonCard';

export default function SupplierCompareScreen() {
  const router = useRouter();
  const [comparison, setComparison] = useState<AlternativeComparison>(
    procurementService.getComparisonData()
  );
  const [proposalMsg, setProposalMsg] = useState<string | null>(null);

  const loadData = () => {
    setComparison(procurementService.getComparisonData());
  };

  useEffect(() => {
    return procurementService.subscribe(loadData);
  }, []);

  const handleSelectProposed = () => {
    const res = procurementService.selectProposedSupplier(
      comparison.id,
      comparison.alternativeSupplier.id
    );
    if (!res.success) {
      Alert.alert('Selection Error', res.error || 'Failed to select proposed supplier.');
      return;
    }
    setProposalMsg(res.message);
    loadData();
  };

  return (
    <SafeAreaView style={styles.safeArea}>
      <ProcurementHeader
        title="Supplier Comparison"
        subtitle="Head-to-Head Commercial &amp; SLA Evaluation Matrix"
        showBack
      />

      <ScrollView style={styles.scroll} contentContainerStyle={styles.scrollContent}>
        {/* Demonstration Data Callout Banner */}
        <View style={styles.demoBanner}>
          <Info size={16} color="#2563EB" />
          <View style={{ flex: 1 }}>
            <Text style={styles.demoBannerTitle}>Demonstration Evaluation Model</Text>
            <Text style={styles.demoBannerText}>
              Comparative benchmark parameters generated by TRUSTCHAIN algorithmic sourcing engine
              for evaluation purposes.
            </Text>
          </View>
        </View>

        {/* Unqualified Supplier Governance Warning */}
        {comparison.alternativeSupplier.qualificationStatus !== 'approved' && (
          <View style={styles.unqualifiedWarning}>
            <AlertTriangle size={16} color="#D97706" />
            <View style={{ flex: 1 }}>
              <Text style={styles.warningTitle}>Supplier Qualification Notice</Text>
              <Text style={styles.warningText}>
                Proposed alternative vendor &quot;{comparison.alternativeSupplier.name}&quot; status is{' '}
                <Text style={{ fontWeight: '800' }}>PENDING QUALIFICATION</Text>. Corporate policy
                prohibits automated purchase order generation for uncertified suppliers. Selection
                creates a sourcing proposal only.
              </Text>
            </View>
          </View>
        )}

        {/* Selected Proposal Alert */}
        {proposalMsg && (
          <View style={styles.proposalNotice}>
            <CheckCircle2 size={16} color="#15803D" />
            <Text style={styles.proposalNoticeText}>{proposalMsg}</Text>
          </View>
        )}

        {/* Comparison Target Info */}
        <View style={styles.targetCard}>
          <Text style={styles.targetLabel}>COMMODITY BENCHMARK</Text>
          <Text style={styles.targetTitle}>{comparison.productName}</Text>
          <Text style={styles.targetSku}>SKU: {comparison.productSku}</Text>
        </View>

        {/* Comparison Matrix Table Card */}
        <SupplierComparisonCard comparison={comparison} />

        {/* Actions Bar */}
        <View style={styles.actionsPanel}>
          <Text style={styles.actionsTitle}>Sourcing Workflow Decisions</Text>
          <Text style={styles.actionsSub}>
            Take governance action on the evaluated alternate supplier proposal.
          </Text>

          {/* Action 1: Select Proposed Supplier */}
          <Pressable style={styles.selectBtn} onPress={handleSelectProposed}>
            <FileCheck size={18} color="#FFFFFF" />
            <Text style={styles.selectBtnText}>
              Select Proposed Supplier as Sourcing Proposal
            </Text>
          </Pressable>

          <View style={styles.secondaryBtnRow}>
            {/* Action 2: View Supplier Details */}
            <Pressable
              style={styles.viewSuppBtn}
              onPress={() =>
                router.push(
                  `/(protected)/procurement-approver/suppliers/${comparison.alternativeSupplier.id}` as any
                )
              }
            >
              <Building size={16} color="#8B5CF6" />
              <Text style={styles.viewSuppBtnText}>Vendor Profile</Text>
            </Pressable>

            {/* Action 3: Return to Request Review */}
            <Pressable
              style={styles.returnReviewBtn}
              onPress={() =>
                router.push(
                  `/(protected)/procurement-approver/requests/${comparison.requestId || 'PR-2026-089'}` as any
                )
              }
            >
              <ArrowLeft size={16} color="#475569" />
              <Text style={styles.returnReviewBtnText}>Back to Review</Text>
            </Pressable>
          </View>
        </View>

        <View style={{ height: 100 }} />
      </ScrollView>

      <ProcurementBottomNav />
    </SafeAreaView>
  );
}

